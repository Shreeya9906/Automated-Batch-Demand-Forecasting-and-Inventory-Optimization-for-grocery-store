// Helper to generate consistent daily dates
function getRelativeDate(offsetDays) {
  const d = new Date();
  d.setDate(d.getDate() + offsetDays);
  return d.toISOString().split('T')[0];
}

// Generate realistic 14 days historical actuals and 30 days forecasts for each SKU
function generateTimeSeriesData(baseDemand, variance) {
  const history = [];
  for (let i = 14; i >= 1; i--) {
    const dayFactor = 1 + Math.sin(i * 0.8) * 0.15;
    const noise = ((i % 5) - 2) * variance * 0.4;
    history.push({
      date: getRelativeDate(-i),
      actual: Math.max(10, Math.round(baseDemand * dayFactor + noise)),
    });
  }

  const futureForecast = [];
  for (let i = 0; i < 30; i++) {
    const trendFactor = 1 + (i * 0.004) + Math.cos(i * 0.6) * 0.12;
    const predicted = Math.max(10, Math.round(baseDemand * trendFactor));
    futureForecast.push({
      date: getRelativeDate(i),
      predicted,
      lower: Math.round(predicted * 0.9),
      upper: Math.round(predicted * 1.1),
    });
  }

  return { history, futureForecast };
}

